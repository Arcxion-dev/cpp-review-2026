//------------------------------------------------------------------
// [문제] 프로그램이 정상 실행되는 NUM 의 최대값을 구하여라.
// a 의 값을 1부터 NUM 까지 int 값으로 assign 한다
// 앞에서부터 100개, 뒤에서부터 100개 출력
//
// 버그 : 주석의 "4 * 2^8 = 1024 = 1mb" 는 틀림
//        1KB = 2^10 바이트, 1MB = 2^20 바이트 = 1024 * 1024
//        스택 1MB / int 4바이트 = 1024 * 1024 / 4 = 262144 개 → 이보다 조금 작아야 한다
//------------------------------------------------------------------

#include<iostream>

int main()
{
	const int NUM{ 250'000 };
	int a[NUM];

	for (int i = 0; i < NUM; ++i) {
		a[i] = i + 1;
	}

	for (int i = 0; i < 100; ++i) {
		std::cout << a[i] << ' ';
	}
	std::cout << std::endl;
	std::cout << std::endl;

	for (int i = 0; i < 100; ++i) {
		std::cout << a[NUM - 1 - i] << ' ';
	}
	std::cout << std::endl;
}
