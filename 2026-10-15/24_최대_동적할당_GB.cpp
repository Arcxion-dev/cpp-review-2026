//------------------------------------------------------------------
// [문제] 내 컴퓨터에서 확보할 수 있는 최대 동적 할당 메모리를 화면에 출력
// 한번에 1GB 씩 할당
// 버그 : new int[250'000] 은 1MB (250'000 * 4 = 100만 바이트)
//        1GB 는 new int[250'000'000]
// ※ 실제로 메모리를 끝까지 잡는 실습이라 컴퓨터가 잠시 느려질 수 있다
//------------------------------------------------------------------

#include<iostream>

int main()
{
	size_t i{};
	while (true) {
		try {
			new int[250'000'000];
			++i;
		}
		catch (...) {
			std::cout << "이 컴퓨터는 " << i << " GB 할당가능" << std::endl;
			break;
		}
	}
}
