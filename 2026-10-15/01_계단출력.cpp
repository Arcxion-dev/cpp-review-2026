//------------------------------------------------------------------
// [문제] "안녕? C++" 를 10번 출력하되, 줄마다 한 글자씩 오른쪽으로 이동해 출력하라
// 버그 : 공백을 endl 뒤에 찍어서 한 줄씩 밀렸음 → 공백을 먼저 찍는다
//------------------------------------------------------------------

#include<iostream>

int main()
{
	for (int i = 0; i < 10; ++i) {
		for (int k = 0; k < i; ++k) {
			std::cout << ' ';
		}
		std::cout << "안녕? C++" << std::endl;
	}
}
