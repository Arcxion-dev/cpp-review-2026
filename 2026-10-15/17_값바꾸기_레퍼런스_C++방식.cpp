//------------------------------------------------------------------
// [문제] a 의 값과 b 의 값을 서로 바꿔라
// 다음 코드가 문제없이 실행 되어야 한다
// C++ 의 해결책 - 레퍼런스
//------------------------------------------------------------------

#include<iostream>

void change(int&, int&);

int main()
{
	int a{ 922 }, b{ 2026 };

	change(a, b);
	std::cout << a << ", " << b << std::endl;
}

void change(int& p, int& q)
{
	int t = p;
	p = q;
	q = t;
}
