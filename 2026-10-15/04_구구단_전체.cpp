//------------------------------------------------------------------
// [문제] 구구단 전체를 출력하라
// 버그 : i = 0 부터 돌려서 0단 출력 / i++ 사용 / for 괄호 위치
//------------------------------------------------------------------

#include<iostream>

int main()
{
	for (int i = 1; i <= 9; ++i) {
		for (int j = 1; j <= 9; ++j) {
			std::cout << i << " * " << j << " = " << i * j << std::endl;
		}
		std::cout << std::endl;
	}
}
