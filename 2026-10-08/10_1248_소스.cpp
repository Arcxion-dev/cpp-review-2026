#include<iostream>
#include "save.h"

using namespace std;

int main() {
	save("소스.cpp");

	int* p; //원시 포인터 8바이트짜리 객체. 시작번지가 p이고 스택에 배치.  
	p = new int[100]; //프리스토어에 400바이트 자리 얻음. 그 자리가 p. 즉 포인터가 객체를 포인팅 하고있음
	delete[] p; // 프리스토어 자리를 되돌려놨기에, 스택에서부터 프리스토어를 가르키고 있던 화살표는 이제 허공을 가르킴. 이걸 dangling pointer라고함. 얘넨 조작 금지. undefined behaviour

	p[0] = 333;
	cout << p[0] << endl;

}
