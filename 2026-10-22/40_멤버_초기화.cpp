//------------------------------------------------------------------
// struct 멤버의 초기화
//
// 1. 지역 Point2D a;   → x, y 에 쓰레기값 (초기화 안 됨)
// 2. 전역 Point2D a;   → 0 으로 채워진다
// 3. 멤버를 int x{}; 로 만들면 지역이어도 0
//------------------------------------------------------------------

#include<iostream>

struct Point2D {
	int x{};
	int y{};
	Point2D() = default;
};

int main()
{
	Point2D a;

	std::cout << a.x << ", " << a.y << std::endl;		// 0, 0
}
