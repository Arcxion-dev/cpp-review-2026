//------------------------------------------------------------------
// 생성자 (constructor) - 객체가 생성될 때 호출되는 함수
// · 이름이 class(struct) 이름과 같다
// · 반환 자료형을 쓰지 않는다
//
// 버그 : 생성자 } 뒤의 ; 는 필요 없음 (struct / class 의 } 뒤에만 ;)
//------------------------------------------------------------------

#include<iostream>

struct Point2D {
	int x{};
	int y{};

	Point2D() {
		x = 2;
		y = 3;
	}
};

int main()
{
	Point2D a;

	std::cout << a.x << ", " << a.y << std::endl;		// 2, 3
}
