int main() {
	save("소스.cpp");

		int num{ 0 };
	while (true) {
		cin >> num;

		int* p;


		try {
			p = new int[num]; //시스템매니저한테 메모리 요청, 단 자리 없으면 요청이 실패가능. 반환값으로는 메모리 시작위치를 알려줌. 크기는 이미 아니까 그 범위 안에서 자유롭게 읽고쓸수잇음. 단 넘어가면 꼬인다.
		}
		catch (std::exception& e) {
			cout << "메모리가 고갈되었을 떄 : " << e.what() << endl;
			return 20261006;
		}


		for (int i = 0;i < num; ++i) {
			p[i] = i + 1;
		}

		//합계
		long long sum{};

		for (int i = 0; i < num;++i)
			sum += p[i];
		cout << "1부터 " << num << "까지의 합계 = " << sum << endl;
	}

}
