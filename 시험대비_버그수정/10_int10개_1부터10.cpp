//------------------------------------------------------------------
// [문제] int 10개를 저장할 메모리를 만들고 각 int 의 값을 1부터 10으로 채워라
// 버그 : 문제는 10개인데 100개를 사용했음
//------------------------------------------------------------------

#include<iostream>

int main()
{
	int num[10];

	for (int i = 0; i < 10; ++i) {
		num[i] = i + 1;
	}

	for (int n : num) {
		std::cout << n << " ";
	}
	std::cout << std::endl;
}
