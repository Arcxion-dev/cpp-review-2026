//------------------------------------------------------------------
// [문제] 1부터 100까지의 int 값을 파일 "int 100개.txt" 에 출력하라.
// 버그 : 파일을 열어놓고 화면(cout)에 출력했음 → out 에 출력
//------------------------------------------------------------------

#include<iostream>
#include<fstream>

int main()
{
	std::ofstream out{ "int 100개.txt" };

	for (int i = 0; i < 100; ++i) {
		out << i + 1 << ' ';
	}
}
