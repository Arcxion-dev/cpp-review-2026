//------------------------------------------------------------------
// [문제] 1부터 1000까지의 정수를 화면에 출력하라 (10칸에 맞춰)
//------------------------------------------------------------------

#include<iostream>
#include<format>

int main()
{
	for (int i = 1; i <= 1000; ++i) {
		std::cout << std::format("{:10}", i) << ' ';
	}
	std::cout << std::endl;
}
