//------------------------------------------------------------------
// [문제] 가장 큰 값을 제일 오른쪽으로 옮겨라
//------------------------------------------------------------------

#include<iostream>

int main()
{
	int num[10]{ 3, 4, 9, 2, 5, 0, 7, 1, 8, 6 };

	for (int i = 0; i < 10 - 1; ++i) {
		if (num[i] > num[i + 1]) {
			int temp{ num[i] };
			num[i] = num[i + 1];
			num[i + 1] = temp;
		}
	}

	for (int i = 0; i < 10; ++i) {
		std::cout << num[i] << ' ';
	}
	std::cout << std::endl;
}
