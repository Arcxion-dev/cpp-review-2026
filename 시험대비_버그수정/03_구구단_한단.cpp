//------------------------------------------------------------------
// [문제] 구구단의 단을 입력받아서 그 단을 출력하라
//------------------------------------------------------------------

#include<iostream>

int main()
{
	std::cout << "출력할 단을 입력: ";

	int dan;
	std::cin >> dan;

	if (dan < 1 || dan > 9) {
		std::cout << "1~9 사이의 숫자를 입력하세요." << std::endl;
		return 1;
	}

	for (int i = 1; i <= 9; ++i) {
		std::cout << dan << " * " << i << " = " << dan * i << std::endl;
	}
}
